# Checking if the student has passed or failed the exam

name = input("Enter the student's name: ")
marks = int(input("Enter the marks: "))

if marks >=60:
    print("Congratulations, " + name + "! Your score is " + str(marks) + ", so you have passed the exam.")
else:
    print("Sorry, " + name +"! Your score is " + str(marks) + " so you have failed the exam.")


